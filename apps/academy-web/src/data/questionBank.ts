/**
 * Size of the full adaptive pool, kept as a synchronous constant for the landing
 * page: CORE items plus each generated bank's count from the build-time manifest.
 * The runtime loader re-dedups by id; ids are unique across banks, so this equals
 * the loaded pool's length.
 */
export const BANK_SIZE =
  CORE_ITEMS.length +
  manifest.imported +
  manifest.fab +
  manifest.bowtie +
  manifest.dragdrop +
  manifest.extendedMr +
  manifest.sata;

// Fetched in this order so de-dup's "first occurrence wins" matches the old
// static assembly (CORE first, then imported → … → sata).
const BANK_URLS = [
  importedUrl,
  fabUrl,
  bowtieUrl,
  dragDropUrl,
  extendedMrUrl,
  sataUrl,
];

async function fetchBank(url: string): Promise<Question[]> {
  const res = await fetch(url);
  if (!res.ok) {
    throw new Error(`Failed to load question bank (HTTP ${res.status}): ${url}`);
  }
  return (await res.json()) as Question[];
}

function dedupById(items: Question[]): Question[] {
  const seen = new Set<string>();
  const out: Question[] = [];
  for (const q of items) {
    if (seen.has(q.id)) continue;
    seen.add(q.id);
    out.push(q);
  }
  return out;
}

let pool: Question[] | null = null;
let inflight: Promise<Question[]> | null = null;

/** The assembled pool if it is already loaded (synchronous; no fetch). */
export function loadedQuestionBank(): Question[] | null {
  return pool;
}

/**
 * Assemble the full adaptive pool: CORE items plus every generated bank, fetched
 * on demand and de-duped by id. Memoized - concurrent and repeat callers share a
 * single fetch; a failed load is not cached, so a later retry refetches.
 */
export function loadQuestionBank(): Promise<Question[]> {
  if (pool) return Promise.resolve(pool);
  if (!inflight) {
    inflight = Promise.all(BANK_URLS.map(fetchBank))
      .then((banks) => {
        pool = dedupById([...CORE_ITEMS, ...banks.flat()]);
        inflight = null;
        return pool;
      })
      .catch((err) => {
        inflight = null;
        throw err;
      });
  }
  return inflight;
}
