const GROUP_DIFFICULTY: Record<string, number> = {
  Electrolytes: -1.0,
  "Renal & glucose": -0.8,
  Hematology: -0.7,
  Coagulation: 0.2,
  "Arterial blood gas": 0.9,
  Hepatic: 0.3,
  "Therapeutic drug levels": 1.0,
};

const decimalsOf = (n: number) => {
  const s = String(n);
  const i = s.indexOf(".");
  return i === -1 ? 0 : s.length - i - 1;
};
const round = (v: number, dp: number) => Number(v.toFixed(dp));
const slug = (s: string) =>
  s
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, "-")
    .replace(/^-+|-+$/g, "");

type LabVariant = "below" | "normal" | "above";
const VARIANT_LABEL: Record<LabVariant, string> = {
  below: "below the normal range",
  normal: "within normal limits",
  above: "above the normal range",
};

function genLabItems(): MultipleChoiceQuestion[] {
  const items: MultipleChoiceQuestion[] = [];
  const options = [
    "Below normal limits",
    "Within normal limits",
    "Above normal limits",
  ];

  for (const group of LAB_GROUPS) {
    const base = GROUP_DIFFICULTY[group.group] ?? 0;
    for (const lab of group.values) {
      if (lab.low === null || lab.high === null) continue;
      const { low, high } = lab;
      const dp = Math.min(2, Math.max(decimalsOf(low), decimalsOf(high)));
      const delta = high - low;
      const variants: { v: LabVariant; value: number; offset: number }[] = [
        { v: "below", value: round(low - delta * 0.4, dp), offset: 0.2 },
        { v: "normal", value: round((low + high) / 2, dp), offset: -0.3 },
        { v: "above", value: round(high + delta * 0.4, dp), offset: 0.1 },
      ];
      for (const { v, value, offset } of variants) {
        const correct = v === "below" ? 0 : v === "normal" ? 1 : 2;
        const unit = lab.unit ? ` ${lab.unit}` : "";
        items.push({
          id: `lab-${slug(lab.name)}-${v}`,
          type: "multiple-choice",
          difficulty: base + offset,
          clientNeed: "reduction-of-risk",
          section: 6,
          topic: `Lab values · ${group.group}`,
          stem: `A client's ${lab.name} result is ${value}${unit}. How should the nurse interpret this value?`,
          options,
          correct,
          rationale: `The normal reference range for ${lab.name} is ${low}-${high}${unit}. A result of ${value}${unit} is ${VARIANT_LABEL[v]}.`,
          reference: "Field Guide · Lab Values",
        });
      }
    }
  }
  return items;
}

